def _logo_bytes(color=(20, 80, 40), size=(300, 200)):
    from PIL import Image
    img = Image.new("RGB", size, "white")
    px = img.load()
    for x in range(100, 200):
        for y in range(60, 140):
            px[x, y] = color
    buf = io.BytesIO()
    img.save(buf, "PNG")
    return buf.getvalue()


