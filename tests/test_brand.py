def test_set_and_show_profile(conn):
    ensure_shop(conn, SHOP)
    assert "Ma's Kitchen" in set_shop_name(conn, SHOP, "Ma's Kitchen")
    assert "saved" in set_shop_address(conn, SHOP, "12 Main Rd").lower()
    assert "saved" in set_shop_phone(conn, SHOP, "0821112222").lower()
    msg, _ = handle_text(conn, SHOP, "show my shop profile")
    assert msg.startswith("🏪 *Shop profile*")
    assert "Ma's Kitchen" in msg and "12 Main Rd" in msg and "0821112222" in msg
    assert "Logo: not yet" in msg


