def test_totals_match_ledger(conn, ledger):
    data = reports.statement_data(conn, SHOP, "Sipho")
    assert data["total"] == balance_cents(conn, SHOP, ledger) == 5000
    assert len(data["items"]) == 2
    assert data["payments"] == [{"date": "2026-10-20", "cents": 1000}]


def test_png_and_pdf_branded(conn, ledger, tmp_path):
    data = reports.statement_data(conn, SHOP, "Sipho")
    brand = reports.shop_brand(conn, SHOP)
    pages = reports.render_statement_pngs(data, brand, str(tmp_path / "st"))
    assert len(pages) == 1
    assert open(pages[0], "rb").read(8) == b"\x89PNG\r\n\x1a\n"
    pdf = reports.render_statement_pdf(data, brand, str(tmp_path / "st.pdf"))
    raw = open(pdf, "rb").read()
    assert b"Statement Spaza" in raw and b"Sipho" in raw
    assert b"Generated by Sisi" in raw
    assert b"Please settle by Friday" in raw


def test_multipage_statement(conn, ledger, tmp_path):
    data = reports.statement_data(conn, SHOP, "Sipho")
    data = {**data, "items": data["items"] * 7}  # 14 lines
    pages = reports.render_statement_pngs(
        data, reports.shop_brand(conn, SHOP), str(tmp_path / "st"))
    assert len(pages) == 2


