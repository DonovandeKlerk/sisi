def detect(text: str | None, default: str = "en") -> str:
    """Detect the message language. Ties and unknowns keep the default."""
    toks = re.findall(r"[a-z']+", (text or "").lower())
    if not toks:
        return default if default in LANGS else "en"
    scores = {lang: 0 for lang in LANGS}
    for tok in toks:
        for lang in LANGS:
            if tok in _MARKERS[lang]:
                scores[lang] += 2
            elif any(stem in tok for stem in _STEMS[lang]):
                scores[lang] += 1
    best = max(scores.values())
    winners = [lang for lang in LANGS if scores[lang] == best]
    if best == 0 or len(winners) != 1:
        return default if default in LANGS else "en"
    return winners[0]


@contextlib.contextmanager
def doc_lang(lang: str | None):
    """Render a document (PDF/PNG) in one fixed language.

    Reports always use the owner's saved language and statements the
    customer's language when known, even when the triggering message was
    written in another language. Restores the previous language after.
    """
    code = lang if lang in LANGS else "en"
    token = CURRENT_LANG.set(code)
    try:
        yield code
    finally:
        CURRENT_LANG.reset(token)


def t(key: str, **vars) -> str:
    """Render a user-facing string in the current language."""
    lang = CURRENT_LANG.get()
    if lang not in LANGS:
        lang = "en"
    template = STRINGS.get(lang, {}).get(key)
    if template is None:
        template = STRINGS["en"].get(key, key)
    try:
        return template.format(**vars)
    except (KeyError, IndexError, ValueError):
        return template


