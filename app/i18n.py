def owner_lang(conn, shop_id: str) -> str:
    """The shop's saved language ('en' when unset or unknown)."""
    try:
        row = conn.execute("SELECT language FROM shops WHERE shop_id = ?",
                           (shop_id,)).fetchone()
    except Exception:
        return "en"
    code = normalize_lang(row["language"]) if row else None
    return code or "en"


