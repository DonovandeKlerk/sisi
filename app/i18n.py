def due_short(day_idx: int, date: str, mon_idx: int, hm: str,
              lang: str | None = None) -> str:
    """'Thu 30 Oct at 05:30' in the current language."""
    lang = lang or CURRENT_LANG.get()
    if lang not in LANGS:
        lang = "en"
    day = DAY_SHORT[lang][day_idx % 7]
    mon = MON_SHORT[lang][mon_idx - 1]
    if lang == "en":
        return f"{day} {date} {mon} at {hm}"
    if lang == "af":
        return f"{day} {date} {mon} om {hm}"
    return f"{day} {date} {mon} ngo-{hm}"


